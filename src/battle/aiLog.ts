// AI に渡す「最近のログ」。人が読む画面のログ (Game.log) から、AI に要るものだけを、短い形にして作る (純粋な関数)。
// 1) 向きをそろえる: ログの「あなた」は、先手 (players[0] = 人) のこと。AI の説明 (盤面・選択肢) では、「あなた」は AI 自身。AI が後手のとき、「あなた」と「相手」を入れ替える
// 2) 要らない行を除く: AI 自身のトークン数・API が使えない知らせ・マナを出すだけのタップ (盤面を見れば分かる)
// 3) 決まり文句を短くする: 「あなたが X を唱えた」→「あなた: 唱 X」。カード名と動作だけ残す

const DROP = [/^相手 \(AI\) /, /をタップして.*(マナ)?を出した$/, /^未実装: /, / を支払った \(/];

const swap = (s: string): string => s.replace(/あなた|相手/g, (m) => (m === "あなた" ? "\u0000" : "\u0001")).replace(/\u0000/g, "相手").replace(/\u0001/g, "あなた");

const RULES: [RegExp, string][] = [
  [/^(あなた|相手)が (.+) を唱えた$/, "$1: 唱 $2"],
  [/^(あなた|相手)が (.+) を別のコストで唱えた$/, "$1: 唱(別コスト) $2"],
  [/^(あなた|相手)が (.+) をキッカーを払って唱えた$/, "$1: 唱(キッカー) $2"],
  [/^(あなた|相手)が (.+) を出した$/, "$1: 出 $2"],
  [/^(あなた|相手)が (.+) で攻撃した$/, "$1: 攻撃 $2"],
  [/^(あなた|相手)が (.+)ブロックした$/, "$1: ブロック $2"],
  [/^(あなた|相手)が (.+) の能力 (.+) を起動した$/, "$1: 起動 $2 $3"],
  [/^(あなた|相手)が (.+) の能力を起動した$/, "$1: 起動 $2"],
  [/^(あなた|相手)がカードを (\d+) 枚引いた$/, "$1: ドロー$2"],
  [/^(あなた|相手)がカードを引いた$/, "$1: ドロー"],
  [/^ターン (\d+): (あなた|相手)のターン$/, "T$1 $2"],
  [/^(.+) を打ち消した$/, "打消 $1"],
  [/^(.+) を破壊した$/, "破壊 $1"],
  [/^(.+) を生け贄に捧げた$/, "生贄 $1"],
  [/^(.+) を追放した$/, "追放 $1"],
];

export function compactLog(lines: readonly string[], flip: boolean): string[] {
  const out: string[] = [];
  for (const raw of lines) {
    if (DROP.some((r) => r.test(raw))) continue;
    let s = flip ? swap(raw) : raw;
    for (const [re, to] of RULES) {
      if (re.test(s)) {
        s = s.replace(re, to);
        break;
      }
    }
    out.push(s);
  }
  return out;
}
